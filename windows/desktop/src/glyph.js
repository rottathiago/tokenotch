const mirror = points => points.map(([x, y]) => [1 - x, y]);
const symmetric = half => [...half, ...mirror(half.slice(0, -1).reverse())];
function eye(x) {
  const points = [];
  for (let index = 0; index <= 16; index++) {
    const angle = index * Math.PI / 16;
    points.push([x + Math.cos(angle) * 0.0325, 0.7075 + Math.sin(angle) * 0.0325]);
  }
  for (let index = 0; index <= 16; index++) {
    const angle = index * Math.PI / 16 + Math.PI;
    points.push([x + Math.cos(angle) * 0.0325, 0.6325 + Math.sin(angle) * 0.0325]);
  }
  return points;
}
export const glyphLoops = [
  [...symmetric(head), ...symmetric(jaw)], lens, mirror(lens),
  [...symmetric(faceTop), ...symmetric(faceBottom)], eye(0.37), eye(0.63), ear, mirror(ear),
];
export const glyphPath = glyphLoops.map(loop =>
  `M${loop.map(([x, y]) => `${(x * 100).toFixed(2)},${(y * 100).toFixed(2)}`).join("L")}Z`).join("");

export function glyphMarkup(className = "copilot-glyph") {
  return `<svg class="${className}" viewBox="0 0 100 100" aria-hidden="true" focusable="false"><path fill-rule="evenodd" d="${glyphPath}"/></svg>`;
}
